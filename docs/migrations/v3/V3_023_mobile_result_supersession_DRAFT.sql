CREATE TABLE mobile_result_supersessions (
    operation_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    sync_id BIGINT UNSIGNED NOT NULL,
    test_result_id BIGINT UNSIGNED NOT NULL,
    replacement_result_id BIGINT UNSIGNED NOT NULL,
    superseded_by_user_id BIGINT UNSIGNED NOT NULL,
    audit_log_id BIGINT UNSIGNED NOT NULL,
    previous_revision BIGINT UNSIGNED NOT NULL,
    mobile_revision BIGINT UNSIGNED NOT NULL,
    score_version INT UNSIGNED NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_json LONGTEXT NOT NULL,
    previous_score_json LONGTEXT NOT NULL,
    replacement_score_json LONGTEXT NOT NULL,
    response_json LONGTEXT NOT NULL,
    superseded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_mobile_supersession_sync(sync_id),
    UNIQUE KEY uk_mobile_supersession_source(test_result_id),
    UNIQUE KEY uk_mobile_supersession_replacement(replacement_result_id),
    UNIQUE KEY uk_mobile_supersession_audit(audit_log_id),
    CONSTRAINT fk_mobile_supersession_sync FOREIGN KEY(sync_id) REFERENCES syncs(sync_id),
    CONSTRAINT fk_mobile_supersession_source FOREIGN KEY(test_result_id) REFERENCES test_results(test_result_id),
    CONSTRAINT fk_mobile_supersession_replacement FOREIGN KEY(replacement_result_id) REFERENCES test_results(test_result_id),
    CONSTRAINT fk_mobile_supersession_teacher FOREIGN KEY(superseded_by_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_mobile_supersession_audit FOREIGN KEY(audit_log_id) REFERENCES audit_logs(audit_log_id),
    CONSTRAINT chk_mobile_supersession_distinct CHECK(test_result_id<>replacement_result_id),
    CONSTRAINT chk_mobile_supersession_revision CHECK(previous_revision BETWEEN 1 AND 9007199254740990 AND mobile_revision=previous_revision+1),
    CONSTRAINT chk_mobile_supersession_version CHECK(score_version BETWEEN 1 AND 2147483647),
    CONSTRAINT chk_mobile_supersession_hash CHECK(request_hash REGEXP '^[0-9a-f]{64}$'),
    CONSTRAINT chk_mobile_supersession_request CHECK(JSON_VALID(request_json)),
    CONSTRAINT chk_mobile_supersession_previous CHECK(JSON_VALID(previous_score_json)),
    CONSTRAINT chk_mobile_supersession_replacement CHECK(JSON_VALID(replacement_score_json)),
    CONSTRAINT chk_mobile_supersession_response CHECK(JSON_VALID(response_json))
) ENGINE=InnoDB;
