CREATE TABLE mobile_result_corrections (
    operation_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    reopen_operation_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    sync_id BIGINT UNSIGNED NOT NULL,
    test_result_id BIGINT UNSIGNED NOT NULL,
    corrected_by_user_id BIGINT UNSIGNED NOT NULL,
    audit_log_id BIGINT UNSIGNED NOT NULL,
    previous_score_version INT UNSIGNED NOT NULL,
    score_version INT UNSIGNED NOT NULL,
    mobile_revision BIGINT UNSIGNED NOT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_json LONGTEXT NOT NULL,
    reference_json LONGTEXT NOT NULL,
    response_json LONGTEXT NOT NULL,
    corrected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_mobile_correction_reopen (reopen_operation_uuid),
    UNIQUE KEY uk_mobile_correction_sync (sync_id),
    UNIQUE KEY uk_mobile_correction_result_version (test_result_id,score_version),
    UNIQUE KEY uk_mobile_correction_audit (audit_log_id),
    CONSTRAINT fk_mobile_correction_reopen FOREIGN KEY(reopen_operation_uuid) REFERENCES mobile_result_reopens(operation_uuid),
    CONSTRAINT fk_mobile_correction_sync FOREIGN KEY(sync_id) REFERENCES syncs(sync_id),
    CONSTRAINT fk_mobile_correction_result FOREIGN KEY(test_result_id) REFERENCES test_results(test_result_id),
    CONSTRAINT fk_mobile_correction_teacher FOREIGN KEY(corrected_by_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_mobile_correction_audit FOREIGN KEY(audit_log_id) REFERENCES audit_logs(audit_log_id),
    CONSTRAINT chk_mobile_correction_version CHECK(previous_score_version BETWEEN 1 AND 2147483646 AND score_version=previous_score_version+1),
    CONSTRAINT chk_mobile_correction_revision CHECK(mobile_revision BETWEEN 2 AND 9007199254740991),
    CONSTRAINT chk_mobile_correction_hash CHECK(request_hash REGEXP '^[0-9a-f]{64}$'),
    CONSTRAINT chk_mobile_correction_request CHECK(JSON_VALID(request_json)),
    CONSTRAINT chk_mobile_correction_reference CHECK(JSON_VALID(reference_json)),
    CONSTRAINT chk_mobile_correction_response CHECK(JSON_VALID(response_json))
) ENGINE=InnoDB;
CREATE TABLE mobile_answer_corrections (
    verification_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    operation_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    student_answer_id BIGINT UNSIGNED NOT NULL,
    omr_detection_id BIGINT UNSIGNED NULL,
    answer_verification_id BIGINT UNSIGNED NULL,
    before_json LONGTEXT NOT NULL,
    after_json LONGTEXT NOT NULL,
    client_decided_at VARCHAR(40) NOT NULL,
    UNIQUE KEY uk_mobile_correction_answer (operation_uuid,student_answer_id),
    CONSTRAINT fk_mobile_answer_correction_operation FOREIGN KEY(operation_uuid) REFERENCES mobile_result_corrections(operation_uuid),
    CONSTRAINT fk_mobile_answer_correction_answer FOREIGN KEY(student_answer_id) REFERENCES student_answers(student_answer_id),
    CONSTRAINT fk_mobile_answer_correction_detection FOREIGN KEY(omr_detection_id) REFERENCES omr_detections(omr_detection_id),
    CONSTRAINT fk_mobile_answer_correction_verification FOREIGN KEY(answer_verification_id) REFERENCES answer_verifications(answer_verification_id),
    CONSTRAINT chk_mobile_answer_correction_kind CHECK((omr_detection_id IS NULL)<>(answer_verification_id IS NULL)),
    CONSTRAINT chk_mobile_answer_correction_before CHECK(JSON_VALID(before_json)),
    CONSTRAINT chk_mobile_answer_correction_after CHECK(JSON_VALID(after_json))
) ENGINE=InnoDB;
