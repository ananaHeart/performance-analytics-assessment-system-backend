-- DRAFT after V3_020. Reviewed deployment only; never executed on application startup.
-- Preserve one immutable first-reopen event per official score version. No correction writes in this slice.
CREATE TABLE mobile_result_reopens (
    operation_uuid CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    sync_id BIGINT UNSIGNED NOT NULL,
    test_result_id BIGINT UNSIGNED NOT NULL,
    reopened_by_user_id BIGINT UNSIGNED NOT NULL,
    audit_log_id BIGINT UNSIGNED NOT NULL,
    previous_revision BIGINT UNSIGNED NOT NULL,
    mobile_revision BIGINT UNSIGNED NOT NULL,
    score_version INT UNSIGNED NOT NULL,
    reason_code VARCHAR(50) NOT NULL,
    comment TEXT NULL,
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    request_json LONGTEXT NOT NULL,
    official_score_json LONGTEXT NOT NULL,
    response_json LONGTEXT NOT NULL,
    reopened_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uk_mobile_reopen_sync (sync_id),
    UNIQUE KEY uk_mobile_reopen_result_version (test_result_id,score_version),
    UNIQUE KEY uk_mobile_reopen_audit (audit_log_id),
    CONSTRAINT fk_mobile_reopen_sync FOREIGN KEY (sync_id) REFERENCES syncs(sync_id),
    CONSTRAINT fk_mobile_reopen_result FOREIGN KEY (test_result_id) REFERENCES test_results(test_result_id),
    CONSTRAINT fk_mobile_reopen_teacher FOREIGN KEY (reopened_by_user_id) REFERENCES users(user_id),
    CONSTRAINT fk_mobile_reopen_audit FOREIGN KEY (audit_log_id) REFERENCES audit_logs(audit_log_id),
    CONSTRAINT chk_mobile_reopen_revision CHECK (previous_revision BETWEEN 1 AND 9007199254740990 AND mobile_revision=previous_revision+1),
    CONSTRAINT chk_mobile_reopen_version CHECK (score_version>=1),
    CONSTRAINT chk_mobile_reopen_reason CHECK (CHAR_LENGTH(TRIM(reason_code)) BETWEEN 1 AND 50),
    CONSTRAINT chk_mobile_reopen_comment CHECK (comment IS NULL OR CHAR_LENGTH(comment)<=4000),
    CONSTRAINT chk_mobile_reopen_hash CHECK (request_hash REGEXP '^[0-9a-f]{64}$'),
    CONSTRAINT chk_mobile_reopen_request CHECK (JSON_VALID(request_json)),
    CONSTRAINT chk_mobile_reopen_score CHECK (JSON_VALID(official_score_json)),
    CONSTRAINT chk_mobile_reopen_response CHECK (JSON_VALID(response_json))
) ENGINE=InnoDB;
